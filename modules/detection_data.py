"""
modules/detection_data.py — cycle 3 defensive layer.

Per-technique detection data for every technique in modules/mitre_data.py
TECHNIQUES (58 IDs). Each entry is hand-authored from the technique's real
telemetry, NOT copied from module prose: the 28 prose event-ID mentions in
module recommendation text were treated as leads and kept only where the
ID is genuinely diagnostic for that technique.

Field conventions (kept strict so consumers never misattribute a signal):
  log_sources:      where the telemetry lives (product/log names).
  channels:         Windows event channels that carry the signal.
  windows_event_ids: Security-channel event IDs ONLY. Anything from another
                    channel goes in other_event_ids with its channel named.
  sysmon_event_ids: Microsoft-Windows-Sysmon/Operational IDs.
  other_event_ids:  [{"channel": ..., "ids": [...]}] for non-Security
                    channels (WinRM, PrintService, TaskScheduler, ...).
  edr_notes:        what an EDR / telemetry pipeline should look for.
  sigma_stub:       a minimal, valid Sigma rule skeleton for the technique
                    (status experimental — a starting point to tune, not a
                    production rule). Generated by _stub() below.

Empty ID lists are deliberate: some techniques (cloud token theft, OSINT)
leave no meaningful Windows Security / Sysmon footprint, and inventing an
ID for them would be worse than none. The log_sources and edr_notes still
say where to look.
"""
from __future__ import annotations

import uuid

from modules.mitre_data import TECHNIQUES

_SIGMA_NS = uuid.NAMESPACE_URL


def _stub(tid: str, description: str, logsource: dict,
          selection: dict, level: str) -> dict:
    """Build a minimal valid Sigma rule skeleton for one technique."""
    tech = TECHNIQUES.get(tid, {})
    tactic = tech.get("tactic", "")
    name = tech.get("name", tid)
    return {
        "title": f"WhiteSentinel defensive layer — {name} ({tid})",
        "id": str(uuid.uuid5(_SIGMA_NS,
                             f"https://attack.mitre.org/techniques/{tid}/")),
        "status": "experimental",
        "description": description + " Stub rule: tune thresholds and "
                                     "field names to the local environment "
                                     "before production use.",
        "references": [f"https://attack.mitre.org/techniques/{tid}/"],
        "author": "WhiteSentinel",
        "date": "2026/10/30",
        "logsource": logsource,
        "detection": {
            "selection": selection,
            "condition": "selection",
        },
        "level": level,
        "tags": [f"attack.{tactic}", f"attack.{tid.lower()}"],
    }


