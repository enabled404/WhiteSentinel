def detection_for(tid: str) -> dict | None:
    """Return the detection entry for a technique ID, or None."""
    return DETECTION_DATA.get(tid)


def techniques_with_detection() -> list[str]:
    """All registry techniques that have a detection entry (sorted)."""
    return sorted(DETECTION_DATA)


def sigma_stub_for(tid: str) -> dict | None:
    """Return the Sigma rule stub for a technique ID, or None."""
    entry = DETECTION_DATA.get(tid)
    return dict(entry["sigma_stub"]) if entry else None


def expected_detections_for_finding(finding: dict) -> list[dict]:
    """Expected detections for one finding, from its authoritative IDs.

    Returns one row per technique ID on the finding (mitre_ids), each
    with the detection telemetry a defender should have seen. Findings
    with no IDs produce no expected rows (nothing was attributed).
    """
    rows = []
    for tid in finding.get("mitre_ids", []) or []:
        entry = DETECTION_DATA.get(tid)
        if not entry:
            continue
        tech = TECHNIQUES.get(tid, {})
        rows.append({
            "technique_id": tid,
            "technique_name": tech.get("name", tid),
            "tactic": tech.get("tactic", ""),
            "log_sources": list(entry["log_sources"]),
            "channels": list(entry["channels"]),
            "windows_event_ids": list(entry["windows_event_ids"]),
            "sysmon_event_ids": list(entry["sysmon_event_ids"]),
            "other_event_ids": [dict(x) for x in entry["other_event_ids"]],
            "edr_notes": entry["edr_notes"],
        })
    return rows
